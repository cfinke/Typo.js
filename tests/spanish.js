function run() {
	var utilityDict = new Typo();
	var affData = utilityDict._readFile(chrome.runtime.getURL("tests/dictionaries/es/es.aff"), "UTF-8");
	var wordData = utilityDict._readFile(chrome.runtime.getURL("tests/dictionaries/es/es.dic"), "UTF-8");
	
	var hashDict = new Typo("es", affData, wordData);
	testDictionary(hashDict);
	
	var dict = new Typo("es", null, null, { dictionaryPath : "tests/dictionaries", asyncLoad : true, loadedCallback : function () {
		testDictionary(dict);
	}});
}

function testDictionary(dict) {
	test("Dictionary object attributes are properly set", function () {
		equal(dict.dictionary, "es");
	});

	test("Issue #16: verb forms with enclitic pronouns are generated by suffix rules", function () {
		equal(dict.check("m\u00E1ndanos"), true);
		equal(dict.check("M\u00E1ndanos"), true);
		equal(dict.check("mandadnos"), true);
		equal(dict.check("mand\u00E1ndonos"), true);
		equal(dict.check("d\u00E1melo"), true);
		equal(dict.check("hab\u00E9rmelo"), true);
		equal(dict.check("Dime"), true);

		// "he" is listed without affix flags, so no rule produces "heme". Hunspell rejects it too.
		equal(dict.check("heme"), false);
		equal(dict.check("Heme"), false);
	});
}

addEventListener( "load", run, false );